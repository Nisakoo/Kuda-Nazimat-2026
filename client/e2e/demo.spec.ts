import { expect, test } from '@playwright/test';
import type { Page } from '@playwright/test';

async function walk(page: Page, key: string, milliseconds: number) {
  await page.keyboard.down(key);
  await page.clock.runFor(milliseconds);
  await page.keyboard.up(key);
  await page.clock.runFor(80);
}

test('walks to both NPCs, opens local dialogue, blocks movement and changes camera', async ({ page }) => {
  const errors: string[] = [];
  const requests: string[] = [];
  page.on('pageerror', (error) => errors.push(error.message));
  page.on('request', (request) => requests.push(request.url()));
  await page.route('**/*', (route) => {
    const url = new URL(route.request().url());
    if (url.origin !== 'http://127.0.0.1:4173') return route.abort();
    if (url.pathname === '/config.json') return route.fulfill({ json: { debug: true } });
    return route.continue();
  });
  await page.clock.install();
  await page.goto('/');
  await page.getByRole('button', { name: 'Начать прогулку' }).click();
  const coords = page.getByLabel('Положение игрока');
  await expect(coords).toContainText('Z 6.0');
  await page.keyboard.press('e');
  await page.clock.runFor(60);
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await walk(page, 'w', 1500);
  await walk(page, 'a', 1200);
  await expect(page.getByRole('button', { name: /Поговорить.*Лея/ })).toBeVisible();
  await page.keyboard.press('e');
  await page.clock.runFor(100);
  await expect(page.getByRole('dialog', { name: 'Лея' })).toBeVisible();
  const stopped = await coords.textContent();
  await page.getByRole('textbox', { name: 'Ваш вопрос' }).fill('wasd <img src=x onerror=alert(1)>');
  await page.clock.runFor(500);
  await expect(coords).toHaveText(stopped!);
  await page.getByRole('button', { name: 'Отправить', exact: true }).click();
  await expect(page.getByRole('dialog')).toContainText('wasd <img');
  await expect(page.locator('img')).toHaveCount(0);
  await page.getByRole('button', { name: 'Что такое исторический источник?', exact: true }).click();
  await expect(page.getByRole('dialog')).toContainText('письмо, фотография');
  await page.screenshot({ path: 'test-results/demo-dialog.png' });
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await walk(page, 'd', 2500);
  await expect(page.getByRole('button', { name: /Поговорить.*Марк/ })).toBeVisible();
  await page.keyboard.press('e');
  await page.clock.runFor(100);
  await page.getByRole('button', { name: 'Почему небо голубое?', exact: true }).click();
  await expect(page.getByRole('dialog', { name: 'Марк' })).toContainText('Молекулы воздуха');
  await page.keyboard.press('Escape');
  const before = await page.locator('canvas').screenshot();
  await page.mouse.move(850, 450);
  await page.mouse.down({ button: 'right' });
  await page.mouse.move(1000, 480, { steps: 6 });
  await page.mouse.up({ button: 'right' });
  await page.mouse.wheel(0, 150);
  await page.clock.runFor(100);
  const after = await page.locator('canvas').screenshot();
  expect(after.equals(before)).toBe(false);
  await page.screenshot({ path: 'test-results/demo-gameplay.png' });
  expect(errors).toEqual([]);
  expect(requests.every((url) => new URL(url).origin === 'http://127.0.0.1:4173')).toBe(true);
});

test('pauses, clears held keys on blur, restarts and returns to the welcome screen', async ({ page }) => {
  await page.route('**/config.json', (route) => route.fulfill({ json: { debug: true } }));
  await page.clock.install();
  await page.goto('/');
  await page.getByRole('button', { name: 'Начать прогулку' }).click();
  const coords = page.getByLabel('Положение игрока');
  await page.keyboard.down('w');
  await page.clock.runFor(300);
  await page.evaluate(() => window.dispatchEvent(new Event('blur')));
  await page.clock.runFor(150);
  const stopped = await coords.textContent();
  await page.clock.runFor(500);
  await expect(coords).toHaveText(stopped!);
  await page.keyboard.up('w');
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog', { name: 'Пауза' })).toBeVisible();
  await page.keyboard.down('w');
  await page.clock.runFor(300);
  await page.keyboard.up('w');
  await page.getByRole('button', { name: 'Продолжить', exact: true }).click();
  await page.clock.runFor(300);
  await expect(coords).toHaveText(stopped!);
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Перезапустить сцену', exact: true }).click();
  await expect(coords).toContainText('Z 6.0');
  await expect(page.locator('canvas')).toHaveCount(1);
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'На главный экран', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Начать прогулку' })).toBeVisible();
  await page.getByRole('button', { name: 'Начать прогулку' }).click();
  await expect(page.locator('canvas')).toHaveCount(1);
});

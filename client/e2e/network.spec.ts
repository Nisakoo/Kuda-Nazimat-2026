import { expect, test } from '@playwright/test';
import { expectCapture, resume } from './helpers';

test.beforeEach(async ({ page }) => { await page.route('**/config.json', route => route.fulfill({ json: { mapId: 'demo' } })); });

test('switches to a labelled mock session, exchanges text, handles loss and reconnects cleanly', async ({ page }) => {
  const errors: string[] = []; const sockets: string[] = [];
  page.on('pageerror', (error) => errors.push(error.message));
  page.on('websocket', (socket) => sockets.push(socket.url()));
  await page.clock.install();
  await page.goto('/');
  await page.getByRole('button', { name: 'Настройки', exact: true }).click();
  await page.getByLabel('Режим сессии').selectOption('mock');
  await page.getByLabel('Диагностика').check();
  await page.getByRole('button', { name: 'Применить и открыть карту' }).click();
  await page.clock.runFor(200);
  await expect(page.getByLabel('Состояние связи')).toHaveText('Подключён');
  await page.getByRole('button', { name: 'Начать прогулку' }).click();
  await expectCapture(page, true);
  await page.keyboard.press('Escape');
  await page.getByRole('dialog', { name: 'Пауза' }).getByRole('button', { name: 'Общение', exact: true }).click();
  await expect(page.getByRole('dialog', { name: 'Общение' })).toBeVisible();
  const coordinates = await page.getByLabel('Положение игрока').textContent();
  await page.getByRole('textbox', { name: 'Сообщение игрокам' }).fill('wasd <img src=x onerror=alert(1)>');
  await page.clock.runFor(200);
  await expect(page.getByLabel('Положение игрока')).toHaveText(coordinates!);
  await page.getByRole('button', { name: 'Отправить', exact: true }).click();
  await page.clock.runFor(500);
  await expect(page.getByRole('dialog', { name: 'Общение' })).toContainText('wasd <img');
  await expect(page.getByRole('dialog', { name: 'Общение' })).toContainText('Сообщение получено тестовым транспортом');
  await expect(page.locator('img')).toHaveCount(0);
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Проверить разрыв связи' }).click();
  await expect(page.getByLabel('Состояние связи')).toHaveText('Связь потеряна');
  await expect(page.getByRole('button', { name: 'Продолжить', exact: true })).toBeDisabled();
  await page.getByRole('dialog', { name: 'Пауза' }).getByRole('button', { name: 'Повторить подключение' }).click();
  await page.clock.runFor(200);
  await page.getByRole('button', { name: 'Начать прогулку' }).click();
  await expectCapture(page, true);
  await expect(page.locator('canvas')).toHaveCount(1);
  await page.screenshot({ path: 'test-results/network-mock.png' });
  expect(sockets).toEqual([]); expect(errors).toEqual([]);
});

test('changes the map and restores local play after an unauthorized real session', async ({ page }) => {
  const sockets: string[] = []; page.on('websocket', (socket) => sockets.push(socket.url()));
  await page.goto('/');
  const old = await page.locator('canvas').elementHandle();
  await page.getByRole('button', { name: 'Настройки', exact: true }).click();
  await page.getByLabel('Карта', { exact: true }).fill('science');
  await page.getByLabel('Диагностика').check();
  await page.getByRole('button', { name: 'Применить и открыть карту' }).click();
  await page.getByRole('button', { name: 'Начать прогулку' }).click();
  await expectCapture(page, true);
  await expect(page.getByRole('heading', { name: 'Сады науки' })).toBeVisible();
  await expect(page.getByLabel('Положение игрока')).toContainText('Z 38.0');
  expect(await old!.evaluate((element) => element.isConnected)).toBe(false);
  await page.keyboard.press('Escape');
  await page.getByRole('dialog', { name: 'Пауза' }).getByRole('button', { name: 'Настройки', exact: true }).click();
  await page.getByLabel('Режим сессии').selectOption('online');
  await page.getByRole('button', { name: 'Применить и открыть карту' }).click();
  await expect(page.getByRole('alert')).toContainText(/серверная сессия/i);
  await expect(page.locator('canvas')).toHaveCount(0);
  await page.getByRole('alert').getByRole('button', { name: 'Настройки', exact: true }).click();
  await page.getByLabel('Режим сессии').selectOption('local');
  await page.getByRole('button', { name: 'Применить и открыть карту' }).click();
  await page.getByRole('button', { name: 'Начать прогулку' }).click();
  await expectCapture(page, true);
  expect(sockets).toEqual([]);
});

test('receives correlated NPC replies through the mock session', async ({ page }) => {
  await page.clock.install(); await page.goto('/');
  await page.getByRole('button', { name: 'Настройки', exact: true }).click();
  await page.getByLabel('Режим сессии').selectOption('mock');
  await page.getByRole('button', { name: 'Применить и открыть карту' }).click();
  await page.clock.runFor(200);
  await page.getByRole('button', { name: 'Начать прогулку' }).click(); await expectCapture(page, true);
  await page.keyboard.down('w'); await page.clock.runFor(1500); await page.keyboard.up('w');
  await page.keyboard.down('a'); await page.clock.runFor(1200); await page.keyboard.up('a');
  await page.clock.runFor(200);
  await page.keyboard.press('e'); await page.clock.runFor(200);
  await expect(page.getByRole('dialog', { name: 'Лея' })).toContainText('Тестовый обмен');
  await page.getByRole('textbox', { name: 'Ваш вопрос' }).fill('История');
  await page.getByRole('button', { name: 'Отправить', exact: true }).click();
  await page.clock.runFor(600);
  await expect(page.getByRole('dialog', { name: 'Лея' })).toContainText('Тестовый ответ на «История»');
  await page.keyboard.press('Escape'); await resume(page);
});

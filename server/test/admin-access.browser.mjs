import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { spawnSync } from 'node:child_process';
import { dirname, join, resolve } from 'node:path';
import { rm, writeFile, mkdir } from 'node:fs/promises';
import { chromium, expect } from '../../client/node_modules/@playwright/test/index.mjs';
import { makeWorld, npc } from './a-helpers.ts';
import { parseConfig } from '../src/app/config.ts';
import { startApplication } from '../src/app/application.ts';
import { createGame } from '../src/game/index.ts';
import { memoryLogger } from '../src/common/logger.ts';
import { lanAddresses } from '../src/common/network.ts';

const world = await makeWorld([npc('guide', 0, 6, { assetId: 'guide-model' })]);
const root = dirname(world.worldDir);
const configPath = join(root, 'config.json');
await writeFile(join(root, 'index.html'), 'fixture');
const input = { ...world, clientDir: root, dbPath: join(root, 'game.sqlite'), defaultMap: 'test', host: '0.0.0.0', auth: { passwordless: false } };
await writeFile(configPath, JSON.stringify(input));
const command = (...args) => {
  const result = spawnSync(process.execPath, [resolve('server/src/cli/auth.ts'), ...args, '--config', configPath, '--env', 'production'], { encoding: 'utf8' });
  assert.equal(result.status, 0, result.stderr); return result.stdout;
};
const created = command('create-admin', 'Учитель');
const temporary = /Временный пароль: (\S+)/.exec(created)[1];
assert.match(command('list'), /admin/);
const config = { ...parseConfig(input, configPath, 'production'), port: 0 };
const logger = memoryLogger();
let app, browser;
try {
  app = await startApplication(config, createGame, logger);
  const port = app.server.address().port;
  const address = lanAddresses().find(a => a.kind !== 'link-local')?.address || '127.0.0.1';
  const origin = 'http://' + address + ':' + port;
  const local = 'http://127.0.0.1:' + port;
  const json = async (path, data, token) => {
    const res = await fetch(origin + path, { method: 'POST', headers: { 'Content-Type': 'application/json', ...(token ? { Authorization: 'Bearer ' + token } : {}) }, body: JSON.stringify(data) });
    return { status: res.status, body: await res.json().catch(() => null) };
  };
  assert.equal((await fetch(origin + '/api/admin/status')).status, 401);
  if (address !== '127.0.0.1') assert.equal((await fetch(origin + '/operator')).status, 404);
  const player = await json('/api/auth/register', { name: 'Игрок', password: 'ИгрокПароль42' });
  assert.equal((await fetch(origin + '/api/admin/status', { headers: { Authorization: 'Bearer ' + player.body.token } })).status, 403);
  assert.equal((await json('/api/admin/dev', {})).status, 403);
  browser = await chromium.launch({ headless: true, executablePath: process.env.OPERATOR_CHROMIUM_EXECUTABLE || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' });
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(origin + '/admin');
  await expect(page.locator('#admin-login')).toBeVisible();
  await expect(page.locator('.workspace')).toBeHidden();
  await page.locator('#admin-name').fill('Учитель');
  await page.locator('#admin-password').fill(temporary);
  await page.locator('#admin-submit').click();
  await expect(page.locator('#admin-new-password-row')).toBeVisible();
  await page.locator('#admin-new-password').fill('УчительПароль42');
  await page.locator('#admin-submit').click();
  await expect(page.locator('.workspace')).toBeVisible();
  await expect(page.locator('#connection')).not.toHaveText('Подключение…');
  assert.deepEqual(await page.evaluate(() => [localStorage.length, sessionStorage.length]), [0, 0]);
  await page.getByRole('link', { name: 'NPC', exact: true }).click();
  await expect(page.locator('#npc-rows')).toContainText('guide');
  await page.locator('#npc-rows').getByRole('button', { name: 'Изменить' }).click();
  await page.locator('#npc-form [name="topic"]').fill('Новая тема администратора');
  page.once('dialog', dialog => dialog.accept());
  await page.locator('#npc-save').click();
  await expect(page.locator('#toast')).toContainText('Изменения сохранены');
  const current = await (await fetch(local + '/api/operator/npcs/guide')).json();
  const history = await (await fetch(local + '/api/operator/journal?target=npc&id=guide')).json();
  assert.equal(history.entries[0].actorName, 'Учитель');
  assert.ok(history.entries[0].actorAccountId);
  // A second editor wins; the first editor must show 409 and preserve the winner.
  const edit = await fetch(local + '/api/operator/npcs/guide', { method: 'PATCH', headers: { 'Content-Type': 'application/json', Origin: local, 'X-Operator': '1' }, body: JSON.stringify({ revision: current.npc.revision, topic: 'Правка второго редактора' }) });
  assert.equal(edit.status, 200);
  await page.locator('#npc-form [name="topic"]').fill('Устаревшая правка');
  page.once('dialog', dialog => dialog.accept());
  await page.locator('#npc-save').click();
  await expect(page.locator('#npc-form-error')).toContainText('Показаны актуальные значения');
  await expect(page.locator('#npc-form [name="topic"]')).toHaveValue('Правка второго редактора');
  await page.getByRole('link', { name: 'Журнал', exact: true }).click();
  await expect(page.locator('#journal-rows')).toContainText('Редактирование');
  const download = page.waitForEvent('download');
  await page.locator('#journal-csv').click(); await download;
  await page.locator('#admin-logout').click();
  await expect(page.locator('#admin-login')).toBeVisible();
  await expect(page.locator('.workspace')).toBeHidden();
  await page.locator('#admin-name').fill('Учитель'); await page.locator('#admin-password').fill('УчительПароль42'); await page.locator('#admin-submit').click();
  await expect(page.locator('.workspace')).toBeVisible();
  command('revoke-admin', 'Учитель');
  await page.locator('#refresh').click();
  await expect(page.locator('#admin-login')).toBeVisible();
  assert.deepEqual(errors, []);
  assert.ok(logger.records.some(r => r.event === 'admin.action'));
  console.log('PASS: CLI create/list/revoke-admin, production LAN admin login, temporary password change, game/admin isolation, NPC revision conflict, author journal, authenticated CSV, logout, role revocation, empty browser storage.');
} finally { await browser?.close(); await app?.stop(); await rm(root, { recursive: true, force: true }); }

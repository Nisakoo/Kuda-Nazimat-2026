import { rm, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { afterEach, expect, it } from 'vitest';
import { io, type Socket } from 'socket.io-client';
import { startApplication } from '../src/app/application.ts';
import { parseConfig } from '../src/app/config.ts';
import { createGame } from '../src/game/index.ts';
import { silentLogger } from '../src/common/logger.ts';
import { parseWorldLifeServerMessage } from '../../shared/world-life/validate.ts';
import type { ShotgunState } from '../../shared/shotgun/types.ts';
import { makeWorld } from './a-helpers.ts';
import { startTrusted } from './tls-helpers.ts';
const cleanups:(()=>Promise<void>)[]=[];
afterEach(async()=>{for(const cleanup of cleanups.splice(0).reverse())await cleanup();});
it('authenticated peers share shots, moving props, reloads and reconnect state; replay cannot fire twice',async()=>{
  const world=await makeWorld([]),root=dirname(world.worldDir);cleanups.push(()=>rm(root,{recursive:true,force:true}));await writeFile(join(root,'index.html'),'<main>test</main>');
  const config={...parseConfig({...world,clientDir:root,dbPath:join(root,'game.sqlite'),defaultMap:'test',host:'127.0.0.1'},join(root,'config.json')),port:0};
  const app=await startTrusted(startApplication,config,createGame,silentLogger);cleanups.push(()=>app.stop());
  const address=app.server.address();if(!address||typeof address==='string')throw Error('No port');const url=`https://127.0.0.1:${address.port}`;
  const guest=async(name:string)=>(await (await fetch(`${url}/api/auth/guest`,{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({name})})).json()) as {token:string};
  const connect=async(token:string)=>{
    const socket:Socket=io(`${url}/game`,{auth:{version:3,token},transports:['websocket'],reconnection:false,forceNew:true,autoConnect:false});cleanups.push(async()=>{socket.disconnect();});
    const states:ShotgunState[]=[];let playerId='';
    socket.on('world-life',(raw:unknown)=>{const packet=parseWorldLifeServerMessage(raw);if(packet.type==='shotgun-state')states.push(packet);});
    socket.on('game',(packet:{type:string;playerId?:string})=>{if(packet.type==='joined')playerId=packet.playerId!;});
    const ready=new Promise<void>((resolve,reject)=>{socket.once('connect',resolve);socket.once('connect_error',reject);});socket.connect();await ready;
    socket.emit('game',{v:3,type:'join',requestId:'join',mapId:'test'});await expect.poll(()=>states.length).toBeGreaterThan(0);
    return {socket,states,get playerId(){return playerId;},last:()=>states.at(-1)!};
  };
  const auth=await Promise.all([guest('Shooter'),guest('Observer')]);
  const a=await connect(auth[0]!.token),b=await connect(auth[1]!.token);
  const before=a.last().props[0]!;
  const request={v:1,type:'shotgun',requestId:'fire-once',action:'fire',yaw:0,pitch:Math.atan2(1.45-.4,4)};
  a.socket.emit('world-life',request);
  await expect.poll(()=>b.last().shots.length).toBe(1);
  await expect.poll(()=>b.last().props[0]!.position.z).toBeLessThan(before.position.z);
  expect(b.last().shots[0]?.playerId).toBe(a.playerId);
  await expect.poll(()=>a.last().weapons.find(w=>w.playerId===a.playerId)?.ammo).toBe(5);
  a.socket.emit('world-life',{...request,requestId:'reload-once',action:'reload'});
  await expect.poll(()=>b.last().weapons.find(w=>w.playerId===a.playerId)?.reloadLeft).toBeGreaterThan(0);
  await expect.poll(()=>a.last().weapons.find(w=>w.playerId===a.playerId)?.ammo,{timeout:5000}).toBe(6);
  a.socket.emit('world-life',request);
  const restored=await connect(auth[0]!.token);
  expect(restored.last().shots).toHaveLength(1);expect(restored.last().weapons.find(w=>w.playerId===a.playerId)?.ammo).toBe(6);
  expect(restored.last().props[0]!.position.z).toBeLessThan(before.position.z);
  await expect.poll(()=>a.socket.connected).toBe(false);
  expect(restored.last().sceneId).toBe(b.last().sceneId);
},15000);
